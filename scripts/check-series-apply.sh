#!/bin/bash
# check-series-apply.sh - which patches of one series apply on its pinned base, in order.
#
#   scripts/check-series-apply.sh <series> <git repo or URL> <base sha> [--write]
#
#   e.g. scripts/check-series-apply.sh monado ~/vr/monado 735e29e4e --write
#
# Applies patches/<series>/*.patch cumulatively in a throwaway clone of <repo> at <base>,
# each with `git am` and, if that fails, `git am -3`; a patch that fails both is skipped
# and the next one is tried on top of what did apply. Prints one line per patch.
#
# With --write it records the result in patches/<series>/applies-on-base.txt, which
# bootstrap-lab.sh reads: listed patches are applied the same way, `# SKIP` lines are not.
# Re-run it with --write whenever a series or its base changes.
#
# Several series here are not linear (docs/147 §5.4): a skipped patch can leave the ones
# after it applying to a tree that never existed on the rig. The list says what applies,
# not what was tested together.

set -u

SERIES="${1:?usage: $0 <series> <repo> <base> [--write]}"
REPO="${2:?usage: $0 <series> <repo> <base> [--write]}"
BASE="${3:?usage: $0 <series> <repo> <base> [--write]}"
WRITE="${4:-}"

HERE="$(cd "$(dirname "$0")/.." && pwd)"
PDIR="$HERE/patches/$SERIES"
[ -d "$PDIR" ] || { echo "no such series: $PDIR" >&2; exit 1; }

WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

git clone -q --no-checkout "$REPO" "$WORK/tree" || { echo "clone of $REPO failed" >&2; exit 1; }
git -C "$WORK/tree" checkout -q "$BASE" || { echo "base $BASE not found in $REPO" >&2; exit 1; }
git -C "$WORK/tree" config user.email check@localhost
git -C "$WORK/tree" config user.name check
FULL_BASE="$(git -C "$WORK/tree" rev-parse HEAD)"

ok=0; ok3=0; fail=0
: > "$WORK/list"
for p in "$PDIR"/*.patch; do
	b="$(basename "$p")"
	if git -C "$WORK/tree" am -q "$p" >/dev/null 2>&1; then
		r="OK   "; ok=$((ok + 1)); echo "$b" >> "$WORK/list"
	else
		git -C "$WORK/tree" am --abort >/dev/null 2>&1
		if git -C "$WORK/tree" am -q -3 "$p" >/dev/null 2>&1; then
			r="OK-3W"; ok3=$((ok3 + 1)); echo "$b" >> "$WORK/list"
		else
			git -C "$WORK/tree" am --abort >/dev/null 2>&1
			r="FAIL "; fail=$((fail + 1)); echo "# SKIP $b" >> "$WORK/list"
		fi
	fi
	echo "$r $b"
done
echo "$SERIES on ${FULL_BASE:0:12}: $ok clean, $ok3 by 3-way merge, $fail skipped"

if [ "$WRITE" = "--write" ]; then
	{
		echo "# Generated by scripts/check-series-apply.sh on $(date +%Y-%m-%d); do not edit by hand."
		echo "# base $FULL_BASE"
		echo "# $ok clean, $ok3 by 3-way merge, $fail skipped (git am, then git am -3)"
		cat "$WORK/list"
	} > "$PDIR/applies-on-base.txt"
	echo "wrote $PDIR/applies-on-base.txt"
fi
[ "$fail" -eq 0 ]
